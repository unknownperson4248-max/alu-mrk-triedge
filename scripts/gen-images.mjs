// Regenerates src/images.js from the files in src/img (run: npm run images)
import { readdirSync, writeFileSync } from 'node:fs';
const files = readdirSync(new URL('../src/img', import.meta.url)).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort();
const id = (f, i) => 'i' + i;
const lines = files.map((f, i) => `import ${id(f, i)} from './img/${f}';`);
lines.push('', 'export const IMAGES = {');
files.forEach((f, i) => lines.push(`  '${f}': [${id(f, i)}, '${/\.png$/i.test(f) ? 'image/png' : 'image/jpeg'}'],`));
lines.push('};', '');
writeFileSync(new URL('../src/images.js', import.meta.url), '// Generated by scripts/gen-images.mjs\n' + lines.join('\n'));
console.log('images:', files.length);
